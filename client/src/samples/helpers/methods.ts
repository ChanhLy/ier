export function targetOptions(type: string | undefined) {
  if (!type) {
    return [];
  }
  const targetMethods = TYPES_TARGETS_METHODS[type];
  return Object.keys(targetMethods).map((target) => {
    return { label: target, value: target };
  });
}
export function methodOptions(type: string | undefined, target: string | undefined) {
  if (!type || !target) {
    return [];
  }
  return TYPES_TARGETS_METHODS[type][target].map((method) => {
    return { label: method, value: method };
  });
}
